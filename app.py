def validate_registration(data):
    errors = []
    required_fields = ["name", "email", "phone", "college", "department",
                        "gender", "city", "participant_category", "attendance_mode"]
    for field in required_fields:
        if not data.get(field):
            errors.append(f"'{field.replace('_',' ').title()}' is required.")

    if data.get("participant_category") and data["participant_category"] not in PARTICIPANT_CATEGORIES:
        errors.append("Please select a valid Participant Category.")

    if data.get("email") and not EMAIL_REGEX.match(data["email"]):
        errors.append("Please enter a valid email address.")

    if data.get("phone") and not PHONE_REGEX.match(data["phone"]):
        errors.append("Please enter a valid 10-digit Indian phone number starting with 6-9.")

    return errors


