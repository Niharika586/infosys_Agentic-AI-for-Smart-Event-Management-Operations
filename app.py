def _compute_system_health():
    start = time.time()
    db_status = "Connected"
    try:
        db.query_one("SELECT 1 as ok")
    except Exception:
        db_status = "Unavailable"
    response_time_ms = round((time.time() - start) * 1000, 2)

    try:
        alert_total = alerts.get_alert_counts().get("total", 0)
    except Exception:
        alert_total = None

    last_intel = db.query_one("SELECT generated_at FROM event_intelligence ORDER BY id DESC LIMIT 1")

    components = [
        {"name": "Application", "status": "Healthy"},
        {"name": "Database", "status": db_status},
        {"name": "Intelligence Engine", "status": "Running"},
        {"name": "Agent Orchestrator", "status": "Running"},
        {"name": "APIs", "status": "Operational"},
    ]
    for c in components:
        try:
            db.execute(
                "INSERT INTO system_health (component, status, response_time_ms) VALUES (?,?,?)",
                (c["name"], c["status"], response_time_ms),
            )
        except Exception:
            pass

    return {
        "components": components,
        "response_time_ms": response_time_ms,
        "active_alerts": alert_total,
        "last_intelligence_update": last_intel["generated_at"] if last_intel else "No data available yet",
        "environment": app.config.get("ENV_NAME", os.environ.get("APP_ENV", "production")),
        "version": "Milestone 4.0",
        "checked_at": datetime.now().isoformat(timespec="seconds"),
    }


