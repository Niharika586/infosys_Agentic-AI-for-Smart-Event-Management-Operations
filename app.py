@app.route("/api/attendees/<int:user_id>", methods=["PUT", "DELETE"])
@login_required()
def api_attendee_detail(user_id):
    if request.method == "DELETE":
        db.execute("DELETE FROM users WHERE id = ?", (user_id,))
        return jsonify({"success": True, "message": "Attendee deleted successfully."})

    data = request.get_json(force=True)
    fields = ["name", "email", "phone", "college", "department",
              "gender", "city", "participant_category", "attendance_mode"]
    updates = {k: v for k, v in data.items() if k in fields}
    if not updates:
        return jsonify({"success": False, "message": "No valid fields to update."}), 400

    set_clause = ", ".join(f"{k} = ?" for k in updates)
    params = list(updates.values()) + [user_id]
    db.execute(f"UPDATE users SET {set_clause} WHERE id = ?", params)
    return jsonify({"success": True, "message": "Attendee updated successfully."})


