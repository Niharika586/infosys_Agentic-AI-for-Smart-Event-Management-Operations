@app.route("/register", methods=["GET", "POST"])
def register():
    if request.method == "POST":
        data = {
            "name": request.form.get("name", "").strip(),
            "email": request.form.get("email", "").strip().lower(),
            "phone": request.form.get("phone", "").strip(),
            "college": request.form.get("college", "").strip(),
            "department": request.form.get("department", "").strip(),
            "gender": request.form.get("gender", "").strip(),
            "city": request.form.get("city", "").strip(),
            "participant_category": request.form.get("participant_category", "").strip(),
            "attendance_mode": request.form.get("attendance_mode", "").strip(),
        }

        errors = validate_registration(data)
        if errors:
            for e in errors:
                flash(e, "error")
            return render_template("register.html", form_data=data, categories=PARTICIPANT_CATEGORIES)

        existing = db.query_one("SELECT id FROM users WHERE email = ?", (data["email"],))
        if existing:
            flash("This email is already registered. Duplicate registrations are not allowed.", "error")
            return render_template("register.html", form_data=data, categories=PARTICIPANT_CATEGORIES)

        user_id = db.execute(
            """INSERT INTO users (name, email, phone, college, department, gender,
               city, participant_category, attendance_mode) VALUES (?,?,?,?,?,?,?,?,?)""",
            (data["name"], data["email"], data["phone"], data["college"], data["department"],
             data["gender"], data["city"], data["participant_category"],
             data["attendance_mode"]),
        )

        registration_id = generate_registration_id(user_id)
        user_row = db.query_one("SELECT * FROM users WHERE id = ?", (user_id,))
        qr_data = build_qr_payload({**user_row, "registration_id": registration_id})
        db.execute(
            "UPDATE users SET registration_id = ?, qr_code = ? WHERE id = ?",
            (registration_id, qr_data, user_id),
        )

        flash("Registration successful! Your Registration ID is {}".format(registration_id), "success")
        return redirect(url_for("register_success", user_id=user_id))

    return render_template("register.html", form_data={}, categories=PARTICIPANT_CATEGORIES)


