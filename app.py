def get_category_counts(users):
    """Return an OrderedDict-like list of (category, count) for every
    Participant Category, in the canonical PARTICIPANT_CATEGORIES order."""
    from collections import Counter
    counter = Counter(u.get("participant_category", "N/A") for u in users)
    return [(cat, counter.get(cat, 0)) for cat in PARTICIPANT_CATEGORIES]


