@app.route("/api/checkin", methods=["POST"])
@login_required()
def api_checkin():
    data = request.get_json(force=True)
    code = data.get("code", "").strip()

    user = find_user_by_scan_code(code)

    if not user:
        return jsonify({"success": False, "message": "Invalid code / attendee not found."}), 404

    if user["checked_in"]:
        return jsonify({"success": False, "message": f"{user['name']} is already checked in."})

    db.execute("UPDATE users SET checked_in = 1 WHERE id = ?", (user["id"],))
    db.execute("INSERT INTO attendance (user_id, status) VALUES (?, 'Present')", (user["id"],))

    checkin_row = db.query_one(
        "SELECT check_in_time FROM attendance WHERE user_id = ? ORDER BY check_in_time DESC LIMIT 1",
        (user["id"],),
    )
    user["check_in_time"] = checkin_row["check_in_time"] if checkin_row else None
    user["checked_in"] = 1

    total = db.query_one("SELECT COUNT(*) as c FROM users")["c"]
    checked_in = db.query_one("SELECT COUNT(*) as c FROM users WHERE checked_in = 1")["c"]

    return jsonify({
        "success": True,
        "message": f"{user['name']} checked in successfully!",
        "user": user,
        "checked_in_count": checked_in,
        "total": total,
    })


