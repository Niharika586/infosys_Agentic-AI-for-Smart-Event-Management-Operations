def generate_registration_id(user_id):
    """Generate a Registration ID like REG-2026-0001."""
    return f"REG-{datetime.now().year}-{int(user_id):04d}"


def build_qr_payload(user):
    """Build the JSON payload embedded inside a participant's QR code."""
    return json.dumps({
        "registration_id": user.get("registration_id"),
        "name": user.get("name"),
        "email": user.get("email"),
        "phone": user.get("phone"),
        "participant_category": user.get("participant_category"),
    })


def generate_qr_image_bytes(payload_text):
    """Generate a PNG QR code image (bytes) for the given text payload."""
    if not qrcode:
        return None
    img = qrcode.make(payload_text)
    buf = io.BytesIO()
    img.save(buf, format="PNG")
    buf.seek(0)
    return buf


def find_user_by_scan_code(code):
    """
    Resolve a scanned/entered check-in code to a user row. Supports:
      - Full JSON QR payload (as generated by build_qr_payload)
      - A bare Registration ID (e.g. REG-2026-0001)
      - A numeric attendee ID or an email address (manual entry)
    """
    code = (code or "").strip()
    if not code:
        return None

    # JSON QR payload
    try:
        payload = json.loads(code)
        if isinstance(payload, dict) and payload.get("registration_id"):
            return db.query_one(
                "SELECT * FROM users WHERE registration_id = ?", (payload["registration_id"],)
            )
    except (ValueError, TypeError):
        pass

    # Bare Registration ID
    if code.upper().startswith("REG-"):
        return db.query_one("SELECT * FROM users WHERE registration_id = ?", (code,))

    # Manual entry: numeric ID or email
    return db.query_one("SELECT * FROM users WHERE id = ? OR email = ?", (code, code))


